"""
fda_importer.py — Convert real FDA enforcement documents into calibration items.

Sources supported
-----------------
- FDA Warning Letters  (HTML, publicly available)
- FDA 483 observations (plain text pasted or loaded from file)
- Any raw regulatory enforcement text

Workflow
--------
1. Fetch document text from a URL or file path
2. LLM reads the document and extracts distinct compliance observations
3. Each observation becomes a task dict with source_type="real"
4. Tasks enter the normal calibration pipeline (Calibrator + Database)

Why this matters
----------------
Synthetic items are generated by the same LLM that solves them, creating a
closed loop. Real FDA enforcement documents represent actual compliance failures
that real companies made and FDA officially cited. Items derived from them have
ground-truth difficulty grounded in regulatory practice, not model priors.

Usage
-----
    python fda_importer.py --url <fda_warning_letter_url>
    python fda_importer.py --file <path_to_text_file>
    python fda_importer.py --url <url> --dry-run   # extract only, no calibration
"""

