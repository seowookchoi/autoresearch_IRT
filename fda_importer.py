def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=(
            "Import real FDA enforcement documents into the compliance item bank. "
            "Fetches or reads a document, extracts compliance scenarios, calibrates "
            "them with the Vanilla/Augmented solvers, and stores them tagged as "
            "source_type='real'."
        )
    )
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--url",  help="URL of an FDA warning letter or enforcement document")
    src.add_argument("--file", help="Path to a local text file containing the document")

    p.add_argument("--db",        default="compliance_bank.db",
                   help="SQLite database path (default: compliance_bank.db)")
    p.add_argument("--max-items", type=int, default=5,
                   help="Max compliance items to extract per document (default: 5)")
    p.add_argument("--dry-run",   action="store_true",
                   help="Extract and display items but do not calibrate or save")
    p.add_argument("--quiet",     action="store_true",
                   help="Suppress per-step solver logs")
    p.add_argument("--compare",   action="store_true",
                   help="After import, print real vs. synthetic difficulty comparison")
    return p.parse_args()


def _print_task_card(task: dict) -> None:
    print(f"\n  Task ID  : {task['task_id']}")
    print(f"  Domain   : {task['domain']}")
    print(f"  Source   : {task.get('source_ref', 'unknown')}")
    if task.get("source_observation"):
        print(f"  FDA obs  : {task['source_observation'][:120]}")
    print(f"  Context  :\n{textwrap.fill(task['context'], width=78, initial_indent='    ', subsequent_indent='    ')}")
    print(f"  Question :\n{textwrap.fill(task['question'], width=78, initial_indent='    ', subsequent_indent='    ')}")
    print(f"  Gold Std :\n{textwrap.fill(task['gold_standard'], width=78, initial_indent='    ', subsequent_indent='    ')}")


def main() -> None:
    args = _parse_args()

    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        print("ERROR: GROQ_API_KEY environment variable is not set.")
        sys.exit(1)

    client = openai.OpenAI(
        base_url="https://api.groq.com/openai/v1",
        api_key=api_key,
    )

    # -- Fetch document ---------------------------------------------------
    if args.url:
        print(f"\n  Fetching: {args.url}")
        try:
            text = fetch_url(args.url)
        except Exception as exc:
            print(f"  ERROR fetching URL: {exc}")
            sys.exit(1)
        source_ref = args.url
    else:
        print(f"\n  Reading: {args.file}")
        text = load_file(args.file)
        source_ref = args.file

    print(f"  Document length: {len(text):,} characters")

    # -- Extract items ----------------------------------------------------
    print(f"\n  Extracting up to {args.max_items} compliance items…")
    converter = FDAConverter(client, max_items=args.max_items)
    tasks     = converter.convert(text, source_ref=source_ref)

    if not tasks:
        print("  No items extracted. Check the document format and try again.")
        sys.exit(1)

    print(f"\n  Extracted {len(tasks)} item(s):\n")
    for task in tasks:
        _print_task_card(task)

    if args.dry_run:
        print("\n  [dry-run] Skipping calibration and database write.")
        return

    # -- Calibrate --------------------------------------------------------
    db         = Database(args.db)
    calibrator = Calibrator(client, verbose=not args.quiet)

    print(f"\n{'─' * 64}")
    print(f"  Calibrating {len(tasks)} real-world item(s)…")
    print(f"{'─' * 64}")

    for task in tasks:
        db.insert_task(task)
        result = calibrator.calibrate(task)
        db.insert_calibration_result(result)

        status = result["retention_reason"]
        b_str  = f"b={result['irt_b']:.4f}" if result["irt_b"] is not None else "b=n/a"
        print(
            f"  {task['task_id']}  →  {status}  {b_str}"
            f"  [V:{'P' if result['vanilla_pass'] else 'F'}"
            f"  A:{'P' if result['augmented_pass'] else 'F'}]"
        )

    # -- Comparison -------------------------------------------------------
    if args.compare:
        print_comparison(db)

    print(f"\n  Done. {len(tasks)} real-world item(s) added to {args.db}.")


if __name__ == "__main__":
    main()
