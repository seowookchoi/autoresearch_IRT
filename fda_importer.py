def _mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else float("nan")

def _stdev(values: list[float]) -> float:
    if len(values) < 2:
        return float("nan")
    m = _mean(values)
    return (sum((x - m) ** 2 for x in values) / (len(values) - 1)) ** 0.5

def print_comparison(db: Database) -> None:
    """
    Print a side-by-side difficulty distribution comparison:
    real-world items vs. synthetic items.
    """
    groups = db.fetch_b_by_source()
    synth  = sorted(groups.get("synthetic", []))
    real   = sorted(groups.get("real", []))

    bar_width = 40

    def histogram(values: list[float], lo: float = -3.0, hi: float = 3.0,
                  bins: int = 12) -> str:
        if not values:
            return "  (no data)"
        bin_size  = (hi - lo) / bins
        counts    = [0] * bins
        for v in values:
            idx = min(int((v - lo) / bin_size), bins - 1)
            idx = max(0, idx)
            counts[idx] += 1
        max_count = max(counts) or 1
        lines = []
        for i, c in enumerate(counts):
            label = f"{lo + i * bin_size:+.1f}"
            bar   = "█" * int(bar_width * c / max_count)
            lines.append(f"  {label:>6}  {bar:<{bar_width}}  {c}")
        return "\n".join(lines)

    width = 64
    bar   = "─" * width

    print(f"\n{bar}")
    print(f"  Difficulty (b) Distribution: Real vs. Synthetic")
    print(bar)

    print(f"\n  SYNTHETIC  (N={len(synth)} retained items)")
    if synth:
        print(f"  mean={_mean(synth):.3f}  sd={_stdev(synth):.3f}"
              f"  min={min(synth):.3f}  max={max(synth):.3f}")
    print(histogram(synth))

    print(f"\n  REAL-WORLD (N={len(real)} retained items)")
    if real:
        print(f"  mean={_mean(real):.3f}  sd={_stdev(real):.3f}"
              f"  min={min(real):.3f}  max={max(real):.3f}")
    print(histogram(real))

    if synth and real:
        delta = _mean(real) - _mean(synth)
        print(f"\n  Mean b gap (real − synthetic): {delta:+.3f}")
        if delta > 0.3:
            print("  Real items appear harder on average than synthetic items.")
        elif delta < -0.3:
            print("  Real items appear easier on average than synthetic items.")
        else:
            print("  Real and synthetic item difficulty are broadly similar.")
    print(bar)


