# ---------------------------------------------------------------------------
# Document fetching
# ---------------------------------------------------------------------------

_USER_AGENT = (
    "Mozilla/5.0 (compatible; research-bot/1.0; +compliance-irt-research)"
)

def fetch_url(url: str) -> str:
    """
    Fetch a URL and return its content as plain text.
    Strips HTML tags if the response looks like HTML.
    """
    req = urllib.request.Request(url, headers={"User-Agent": _USER_AGENT})
    with urllib.request.urlopen(req, timeout=30) as resp:
        raw = resp.read().decode("utf-8", errors="replace")
    return _strip_html(raw) if "<html" in raw.lower() else raw


def _strip_html(html_text: str) -> str:
    """
    Minimal HTML → plain text conversion without external deps.
    Preserves paragraph structure; removes tags, scripts, styles.
    """
    # Remove script and style blocks
    text = re.sub(r"<(script|style)[^>]*>.*?</\1>", "", html_text,
                  flags=re.DOTALL | re.IGNORECASE)
    # Replace block-level tags with newlines
    text = re.sub(r"<(br|p|li|tr|h[1-6]|div)[^>]*/?>", "\n", text,
                  flags=re.IGNORECASE)
    # Strip remaining tags
    text = re.sub(r"<[^>]+>", "", text)
    # Decode HTML entities
    text = html.unescape(text)
    # Collapse whitespace
    text = re.sub(r"\n{3,}", "\n\n", text)
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


def load_file(path: str) -> str:
    return Path(path).read_text(encoding="utf-8", errors="replace").strip()


# ---------------------------------------------------------------------------
# Conversion prompts
# ---------------------------------------------------------------------------

_CONVERTER_SYSTEM = (
    "You are a biopharma regulatory affairs specialist and instructional designer. "
    "Your task is to read real FDA enforcement documents (warning letters, 483 observations) "
    "and convert each distinct compliance finding into a structured exam-quality scenario. "
    "You extract the facts faithfully — you do not invent or embellish. "
    "You anonymize company names by replacing them with fictional names (e.g., 'NovaBio Inc.'). "
    "Every item you produce must be grounded in the actual regulatory citation from the document."
)

_CONVERTER_USER = """
Below is the text of an FDA enforcement document (warning letter or 483 observation).

Read it carefully and extract up to {max_items} distinct compliance findings.
For each finding, produce one JSON object in this exact structure:

{{
  "domain": "<one of: 21cfr11 | gcp_deviation | promo_review | gmp_deviation | informed_consent | gmp_general | other>",
  "context": "<3-5 sentences describing the situation faithfully but with the real company name replaced by a fictional one. Include concrete details: roles, systems, dates if available, quantities. Do not state the compliance conclusion.>",
  "question": "<One precise question asking whether the described practice is compliant, or what the correct regulatory action is. Must have a single defensible answer.>",
  "gold_standard": "<The correct answer. Must cite the EXACT regulation section(s) that FDA cited in the document (e.g., '21 CFR 211.192', 'ICH E6(R2) §5.18.2'). State the specific obligation or violation precisely.>",
  "source_observation": "<Direct quote or close paraphrase of the key sentence(s) from the original document that this item is based on. Keep under 200 characters.>"
}}

Rules:
- Output a JSON array containing between 1 and {max_items} objects. Nothing else — no markdown, no commentary.
- Each item must correspond to a distinct observation in the document.
- Do not invent findings not present in the document.
- If the document does not contain clear regulatory citations, still extract the finding and note the likely applicable regulation based on the subject matter.
- Anonymize all real company names, product names, and individual names.
- Do not include the compliance conclusion in context or question fields.

--- FDA DOCUMENT ---
{document_text}
"""


# ---------------------------------------------------------------------------
# Converter class
# ---------------------------------------------------------------------------

class FDAConverter:
    """
    Extracts compliance scenarios from real FDA enforcement documents.

    Parameters
    ----------
    client      : openai.OpenAI  (pointed at Groq or any OpenAI-compatible endpoint)
    model       : LLM to use for extraction
    max_items   : Maximum number of items to extract per document
    """

    def __init__(
        self,
        client: openai.OpenAI,
        model: str = "llama-3.3-70b-versatile",
        max_items: int = 5,
    ) -> None:
        self.client    = client
        self.model     = model
        self.max_items = max_items

    def convert(self, document_text: str, source_ref: str = "") -> list[dict]:
        """
        Extract compliance items from document text.

        Returns a list of task dicts ready for calibration, tagged with
        source_type="real" and source_ref=<url or filename>.
        """
        # Truncate very long documents to avoid context limits
        text = document_text[:12_000] if len(document_text) > 12_000 else document_text

        prompt = _CONVERTER_USER.format(
            max_items=self.max_items,
            document_text=text,
        )

        try:
            resp = self.client.chat.completions.create(
                model=self.model,
                max_tokens=4096,
                messages=[
                    {"role": "system", "content": _CONVERTER_SYSTEM},
                    {"role": "user",   "content": prompt},
                ],
            )
            raw = resp.choices[0].message.content.strip()
        except Exception as exc:
            print(f"  [FDAConverter] API error: {exc}")
            return []

        items = self._parse(raw)
        tasks = []
        for item in items:
            domain  = item.get("domain", "other")
            task_id = f"TASK-REAL-{domain.upper()[:8]}-{uuid.uuid4().hex[:8].upper()}"
            tasks.append({
                "task_id":          task_id,
                "domain":           domain,
                "context":          item.get("context", ""),
                "question":         item.get("question", ""),
                "gold_standard":    item.get("gold_standard", ""),
                "source_type":      "real",
                "source_ref":       source_ref,
                "source_observation": item.get("source_observation", ""),
            })
        return tasks

    # ------------------------------------------------------------------
    # Internal
    # ------------------------------------------------------------------

    @staticmethod
    def _parse(raw: str) -> list[dict]:
        """Parse JSON array from LLM response, tolerating markdown fences."""
        cleaned = re.sub(r"^```(?:json)?\s*", "", raw, flags=re.MULTILINE)
        cleaned = re.sub(r"\s*```$",          "", cleaned, flags=re.MULTILINE)
        cleaned = cleaned.strip()

        # Model sometimes returns a single object instead of an array
        if cleaned.startswith("{"):
            cleaned = f"[{cleaned}]"

        try:
            return json.loads(cleaned)
        except json.JSONDecodeError as exc:
            print(f"  [FDAConverter] JSON parse error: {exc}")
            print(f"  Raw response (first 500 chars): {raw[:500]}")
            return []


